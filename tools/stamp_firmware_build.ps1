# PowerShell 5.1: generate exact Git source identity BEFORE CubeIDE compiles main.c.
# If Git/stamp fails, build must fail (never silently claim an old commit).
[CmdletBinding()]
param([string]$RepoRoot = (Split-Path -Parent $PSScriptRoot))
$ErrorActionPreference = 'Stop'
$RepoRoot = [System.IO.Path]::GetFullPath($RepoRoot)
function Read-Git([string[]]$GitArgs) {
    $lines = & git -C $RepoRoot @GitArgs 2>&1
    if ($LASTEXITCODE -ne 0) {
        throw "Git stamp failed ($($GitArgs -join ' ')): $lines"
    }
    return ($lines | Out-String).Trim()
}
$sha = Read-Git -GitArgs @('rev-parse', '--verify', 'HEAD')
if ($sha -cnotmatch '^[0-9a-f]{40}$') {
    throw 'Git HEAD is not a 40-hex commit; refuse to stamp firmware.'
}
$branchResult = & git -C $RepoRoot symbolic-ref --quiet --short HEAD 2>&1
if ($LASTEXITCODE -eq 0) {
    $branch = ($branchResult | Out-String).Trim()
} elseif ($LASTEXITCODE -eq 1) {
    $branch = 'DETACHED'
} else {
    throw "Cannot obtain Git branch: $branchResult"
}
$branch = [regex]::Replace($branch, '[^0-9A-Za-z._/-]', '_')
if ($branch.Length -gt 62) { $branch = $branch.Substring(0, 62) }
$status = Read-Git -GitArgs @('status', '--porcelain', '--untracked-files=normal')
$dirty = if ([string]::IsNullOrWhiteSpace($status)) { 0 } else { 1 }
$utc = [DateTime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ',
    [Globalization.CultureInfo]::InvariantCulture)
$header = @(
    '#ifndef FIRMWARE_BUILD_ID_GENERATED_H'
    '#define FIRMWARE_BUILD_ID_GENERATED_H'
    '/* GENERATED by tools/stamp_firmware_build.ps1; DO NOT EDIT OR COMMIT. */'
    ('#define FW_BUILD_GIT_SHA "{0}"' -f $sha)
    ('#define FW_BUILD_GIT_DIRTY {0}U' -f $dirty)
    ('#define FW_BUILD_GIT_BRANCH "{0}"' -f $branch)
    ('#define FW_BUILD_UTC "{0}"' -f $utc)
    '#endif'
) -join [Environment]::NewLine
$path = Join-Path $RepoRoot 'Core\Inc\firmware_build_id_generated.h'
[IO.File]::WriteAllText($path, $header + [Environment]::NewLine,
    (New-Object System.Text.UTF8Encoding($false)))
Write-Host "STAMPED firmware Git commit=$sha dirty=$dirty branch=$branch builtUtc=$utc"
